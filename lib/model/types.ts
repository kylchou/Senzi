// Types shared by the model, the collectors and the backtest.

export type SourceId =
  | 'npm'
  | 'pypistats'
  | 'github'
  | 'sec_edgar'
  | 'greenhouse'
  | 'ashby'
  | 'workable'
  | 'tranco'
  | 'hn_algolia'
  | 'sponsor';

export type Provenance = 'scraped' | 'sponsor_provided';

/**
 * One observed value. Dates are UTC calendar days (YYYY-MM-DD); timestamps are ISO strings.
 * `availableAt` is when the value became publicly knowable, which is what the
 * backtest filters on so it never uses data from the future.
 */
export interface DataPoint {
  companyId: string;
  metricId: string;
  source: SourceId;
  value: number;
  periodStart: string;
  periodEnd: string;
  availableAt: string;
  fetchedAt: string;
  sourceUrl: string;
  provenance: Provenance;
  /** True for demo values that were made up. Always false for scraped data. */
  simulated: boolean;
  note?: string;
}

export type MetricKind = 'daily_count' | 'weekly_count' | 'snapshot' | 'event' | 'rank';

export interface MetricDef {
  id: string;
  companyId: string;
  source: SourceId;
  label: string;
  unit: string;
  kind: MetricKind;
  /** Lower is better for ranks. */
  higherIsBetter: boolean;
}

/** "Will <metric> in the 7 days ending <windowEnd> be at least <threshold>?" */
export interface ThresholdQuestion {
  id: string;
  companyId: string;
  metricId: string;
  threshold: number;
  /** Last day (inclusive) of the 7-day window. */
  windowEnd: string;
  windowDays: 7;
  /** The question as shown to users, generated by questionText(). */
  text: string;
  /** Named before the question opens. Also used to resolve it. */
  resolutionSource: { source: SourceId; url: string; description: string };
  /** When the question opens (opening baseline is computed as of this time). */
  opensAt: string;
  /** Present on demo questions that intentionally sit in the past. */
  note?: string;
}

export type BaselineStatus = 'ok' | 'insufficient_data' | 'observed';
export type ModelConfidence = 'low' | 'medium' | 'high';

export interface InputUsed {
  metricId: string;
  source: SourceId;
  provenance: Provenance;
  simulated: boolean;
  /** What the input did: fit the trend, fill weeks the scraped data lacked, or remove npm-wide moves. */
  role: 'trend' | 'sponsor_fill' | 'market_index';
  points: number;
  periodStart: string | null;
  periodEnd: string | null;
}

export interface SourceRef {
  source: SourceId;
  url: string;
  fetchedAt: string | null;
}

export interface MethodInfo {
  name: string;
  version: string;
  description: string;
  /** Numbers behind the result, for the methodology panel and debugging. */
  details: {
    /** Last day of data the result is based on. The result only changes when this data changes. */
    dataThrough: string | null;
    weeksUsed: number;
    horizonWeeks: number | null;
    /** Weekly growth implied by the trend, e.g. 0.012 = +1.2% per week. */
    weeklyGrowth: number | null;
    /** Median forecast of the 7-day total for the question window. */
    forecastMedian: number | null;
    /** 80% forecast range for the 7-day total (10th to 90th percentile). */
    forecastRange80: [number, number] | null;
    lastObservedWeek: { windowEnd: string; total: number } | null;
    mu: number | null;
    sigma: number | null;
    rawProbability: number | null;
    /** Weight on the fitted probability from thin-data shrinkage (1 at 8+ weeks). */
    shrinkWeight: number | null;
    /** Global pull toward 50% applied on top (from the backtest). */
    tailShrink: number;
    bootstrapReplicates: number;
    seed: number | null;
    inputsHash: string;
    /** Set when the forecast is relative to the npm-wide index (lib/model/npm-index.ts). */
    npmIndex?: NpmIndexDetails | null;
  };
}

export interface NpmIndexDetails {
  packages: string[];
  /** Latest week with a complete index; the adjusted series is at this week's npm level. */
  referenceWeek: string;
  /** How strongly the package moves with the index week to week (1 = one for one). */
  beta: number;
  /** Trend of the company's downloads relative to npm, per week (e.g. 0.01 = +1%). */
  relativeWeeklyGrowth: number;
  /** The index's own trend per week, and its change to the reference week from about 4 and 12 weeks before. */
  indexWeeklyTrend: number | null;
  indexMoves: Array<{ since: string; change: number }>;
  /** Log-scale mean and spread of the index move from the reference week to the question window. */
  indexMean: number;
  indexSd: number;
  /** Weeks with missing days that were valued relative to npm instead of left out. */
  recoveredWeeks: string[];
}

export interface BaselineResult {
  questionId: string;
  questionText: string;
  status: BaselineStatus;
  /** Point estimate from the full fit, after shrinkage. Null when there isn't enough data. */
  probability: number | null;
  low: number | null;
  high: number | null;
  /** Shown next to the band. It is not a confidence interval on the outcome. */
  bandLabel: 'model uncertainty';
  asOf: string;
  method: MethodInfo;
  confidence: ModelConfidence | null;
  inputsUsed: InputUsed[];
  sources: SourceRef[];
  /** Data the model wanted but didn't have. */
  missing: string[];
  notes: string[];
}
